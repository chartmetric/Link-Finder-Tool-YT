// Read-only reconstruction of partial metadata captures. Never acknowledges
// admissions, changes approvals, repeats requests or accepts artist ownership.
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {digest} from './youtube-video-discovery-offline.mjs';
import {normalizeYoutubeChannel} from './youtube-ownership-transport.mjs';
import {boundYoutubeCapture,returnedYoutubeUrl} from './youtube-ownership-policy.mjs';
import {connectSavedBatchPool} from './instagram-saved-batch-gate.mjs';
import {select} from './instagram-artist-metadata-overlay.mjs';
const id='youtube-batch-channel-checks-direct-100-refreshed-2026-11-13';
const source='generated-artifacts/'+id,output='generated-artifacts/youtube-direct-channel-check-partial-results-2026-11-13';
const read=async file=>JSON.parse(await fs.readFile(file));
const cell=v=>{let s=String(v??'');if(/^[=+\-@\t\r\n]/u.test(s))s="'"+s;return '"'+s.replaceAll('"','""')+'"';};
const csv=rows=>'\ufeff'+rows.map(r=>r.map(cell).join(',')).join('\r\n');
const save=(name,data)=>fs.writeFile(output+'/'+name,typeof data==='string'?data:JSON.stringify(data,null,2),{flag:'wx'});
assert.deepEqual(process.argv.slice(2),['--read-only-export']);
const plan=await read(source+'/plan.json'),pool=await connectSavedBatchPool();let client,admissions,runs;
try{
  client=await pool.connect();await client.query('BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY');
  const ids=plan.children.map(c=>c.id);
  runs=(await client.query('SELECT id,status,reserved_cents,cap_cents FROM youtube_video_identity_runs WHERE id=ANY($1::text[]) ORDER BY id',[ids])).rows;
  admissions=(await client.query(`SELECT run_id,operation_key,profile_id,cm_artist,status,reserved_cents,
    input_sha256,receipt_sha256,raw_sha256 FROM youtube_video_identity_admissions
    WHERE run_id=ANY($1::text[])`,[ids])).rows;
  await client.query('COMMIT');
}catch(e){if(client)await client.query('ROLLBACK');throw e;}finally{client?.release();await pool.end();}
assert.ok(runs.every(r=>r.status==='completed'||r.status==='stopped'));
assert.equal(runs.reduce((n,r)=>n+r.reserved_cents,0),admissions.reduce((n,a)=>n+a.reserved_cents,0));
const catalog=await select(`SELECT toString(l.profile_id) profile_id,toString(p.cm_source_id) cm_artist,
  a.account_url FROM new_vertical.l_profile_account l FINAL
  INNER JOIN new_vertical.account a FINAL ON a.id=l.account_id
  LEFT JOIN new_vertical.profile p FINAL ON p.id=l.profile_id
  WHERE lower(a.platform)='youtube' AND notEmpty(trim(ifNull(a.account_url,'')))`);
const captures=[];
for(const child of plan.children){
  const folder='generated-artifacts/'+child.id,p=await read(folder+'/plan.json');
  assert.equal(digest(p),child.planSha256);
  for(const op of p.operations){
    const a=admissions.find(a=>a.run_id===child.id&&a.operation_key===op.key);
    if(!a)continue;
    assert.equal(a.profile_id,op.profileId);assert.equal(a.cm_artist,op.cmArtist);assert.equal(a.input_sha256,op.inputSha256);
    const receipt=await read(folder+'/receipts/'+digest(op.key)+'.json');
    assert.equal(receipt.rawPath,'receipts/'+digest(op.key)+'.raw');
    assert.equal(receipt.planSha256,child.planSha256);assert.equal(receipt.operationKey,op.key);
    assert.equal(receipt.inputSha256,op.inputSha256);assert.deepEqual(receipt.request,op.request);
    const raw=await fs.readFile(folder+'/'+receipt.rawPath);assert.equal(digest(raw),receipt.rawBodySha256);
    const body=JSON.parse(raw);assert.equal(receipt.status,200);assert.equal(body.success,true);
    assert.ok(Number.isInteger(body.credits_charged)&&body.credits_charged>=0&&body.credits_charged<=1);
    const capture=normalizeYoutubeChannel({at:receipt.capturedAt,status:receipt.status,kind:'metadata',
      operationKey:op.key,request:op.request,inputSha256:op.inputSha256,data:body},op.targetUrl);
    const bound=boundYoutubeCapture(op.targetUrl,capture);assert.ok(bound);
    if(op.expectedChannelId)assert.equal(bound.body.channelId,op.expectedChannelId);
    const selection=p.selections.find(s=>s.profileId===op.profileId),artist=p.artists.find(s=>s.profileId===op.profileId);
    const conflicts=catalog.filter(r=>{
      const alias=returnedYoutubeUrl(r.account_url);
      return alias&&bound.aliases.some(a=>a.toLowerCase()===alias.toLowerCase())
        &&(String(r.profile_id)!==op.profileId||String(r.cm_artist)!==op.cmArtist);
    });
    if(a.status==='returned'){
      assert.equal(a.receipt_sha256,digest(receipt));assert.equal(a.raw_sha256,digest(raw));
      assert.equal(conflicts.length,0);
    }else{assert.equal(a.status,'admitted');assert.ok(conflicts.length);}
    const topic=bound.body.isAutoGenerated===true||/\s*[-–—]\s*Topic\s*$/iu.test(bound.body.displayName??'');
    captures.push({artist:selection.artist,startingTier:artist.startingTier??selection.tier,currentTier:selection.tier,
      profileId:op.profileId,cmArtist:op.cmArtist,youtubeUrl:'https://www.youtube.com/channel/'+bound.body.channelId,
      requestedUrl:op.targetUrl,channelName:bound.body.displayName,handle:bound.body.handle,
      channelType:topic?'topic':bound.body.isOfficialArtistChannel===true?'official_artist_channel':'unknown',
      channelTypeLabel:topic?'Topic — auto-generated; artist association unverified':
        bound.body.isOfficialArtistChannel===true?'Official Artist Channel badge — artist match unverified':'Channel captured — artist ownership unverified',
      status:a.status==='returned'?'metadata_captured_ownership_unverified':'held_shared_catalog_claim_saved_not_acknowledged',
      sourceRunId:child.id,capturedAt:receipt.capturedAt,receiptSha256:digest(receipt),rawSha256:digest(raw),
      capture,conflicts,ownershipAccepted:false,importEligible:false});
  }
}
assert.equal(captures.length,admissions.length);
const completed=captures.filter(c=>c.status==='metadata_captured_ownership_unverified');
const held=captures.filter(c=>c.status!=='metadata_captured_ownership_unverified');
const headers=['artist','starting_tier','current_tier','profile_id','cm_artist','youtube_url','requested_url','channel_name',
  'handle','channel_type','channel_type_label','status','captured_at','ownership_accepted','import_eligible','result_json'];
const row=c=>[c.artist,c.startingTier,c.currentTier,c.profileId,c.cmArtist,c.youtubeUrl,c.requestedUrl,c.channelName,c.handle,
  c.channelType,c.channelTypeLabel,c.status,c.capturedAt,false,false,JSON.stringify(c)];
await fs.mkdir(output);
await save('youtube-channels-captured.csv',csv([headers,...completed.map(row)]));
await save('youtube-channel-conflicts-held.csv',csv([headers,...held.map(row)]));
const capturedProfiles=new Set(captures.map(c=>c.profileId));
const pending=plan.children.flatMap(c=>c.plan.selections).filter(s=>!capturedProfiles.has(s.profileId));
await save('youtube-channel-checks-still-pending.csv',csv([
  ['artist','current_tier','profile_id','cm_artist','requested_channel_url','status','paid_calls'],
  ...pending.map(s=>[s.artist,s.tier,s.profileId,s.cmArtist,s.url,'Not requested — batch stopped; needs safe continuation',0])]));
const reservedCents=runs.reduce((n,r)=>n+r.reserved_cents,0);
const summary={status:'stopped_shared_catalog_claim',id,sourceArtistDenominator:100,approvedChannelChecks:52,
  providerResponsesSaved:captures.length,metadataCapturesRecorded:completed.length,sharedClaimResponsesHeld:held.length,
  untouchedChannelChecks:pending.length,topicCapturesRecorded:completed.filter(c=>c.channelType==='topic').length,
  reservedCents,approvedMaximumCents:104,maximumUnattemptedCents:pending.length*2,
  latestTierDeferrals:3,otherArtistsNotSelectedEarlier:45,modelCalls:0,catalogWrites:0,
  ownershipAccepted:0,importEligible:0,retries:0,coordinatorWritesDuringExport:0,
  warning:'A shared catalog claim is not proof of a false match. Do not replay the saved held response or treat it as an accepted link.'};
assert.equal(completed.length+held.length+pending.length,52);
assert.ok(reservedCents+summary.maximumUnattemptedCents<=104);
await save('partial-results.json',{summary,runs,captures,pending});
console.log(JSON.stringify(summary));
