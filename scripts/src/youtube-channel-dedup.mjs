// One cache per exact artist. A name or search URL cannot bind channel aliases.
import assert from 'node:assert/strict';
import {boundYoutubeCapture,youtubeOwnershipUrl,evidenceDigest,evaluateYoutubeOwnership} from './youtube-ownership-policy.mjs';
const facts=body=>evidenceDigest({name:body.displayName,description:body.description,
  externalUrls:[...(body.externalUrls??[])].sort(),
  isAutoGenerated:body.isAutoGenerated??null,isOfficialArtistChannel:body.isOfficialArtistChannel??null});
export function createYoutubeChannelCache(artist){
  assert.ok(artist.profileId&&artist.cmArtist);
  const owner={profileId:String(artist.profileId),cmArtist:String(artist.cmArtist)},groups=new Map();
  function assertArtist(current){
    assert.equal(String(current.profileId),owner.profileId);assert.equal(String(current.cmArtist),owner.cmArtist);
  }
  function aliasObservation(primary,candidate,binding){
    (primary.channelAliasObservations??=[]).push({url:candidate.url,title:candidate.title??'',snippet:candidate.snippet??'',
      sourceUrl:candidate.sourceUrl??candidate.url,channelId:binding.body.channelId,
      bindingCaptureSha256:binding.bodySha256,...(candidate.capture?{capture:candidate.capture}:{})});
    candidate.aliasOf=primary.url;candidate.canonicalChannelId=binding.body.channelId;
    return primary;
  }
  return {
    reuse(current,candidate){
      assertArtist(current);
      // Existing observations must be inspected for conflicts, not hidden by
      // an alias discovered earlier in this run.
      if(candidate.capture)return null;
      for(const primary of groups.values()){
        const bound=boundYoutubeCapture(primary.url,primary.capture);
        if(bound&&bound.aliases.includes(youtubeOwnershipUrl(candidate.url)))return aliasObservation(primary,candidate,bound);
      }
      return null;
    },
    observe(current,candidate){
      assertArtist(current);const bound=boundYoutubeCapture(candidate.url,candidate.capture);
      if(!bound)return null;
      const primary=groups.get(bound.body.channelId);
      if(!primary){groups.set(bound.body.channelId,candidate);candidate.canonicalChannelId=bound.body.channelId;return null;}
      if(candidate.contradictoryPair===true||facts(bound.body)!==facts(primary.capture.body)){
        primary.contradictoryPair=true;
        primary.aliasConflictReason='provider_bound_alias_captures_disagree';
        primary.decision=evaluateYoutubeOwnership(current,primary,{contradictoryPair:true});
      }
      return aliasObservation(primary,candidate,bound);
    },
  };
}
