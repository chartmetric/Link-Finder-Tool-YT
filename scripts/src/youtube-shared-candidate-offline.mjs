// Review design only. Not imported by any worker; never returns acceptance.
import assert from 'node:assert/strict';
import {evidenceDigest as hash, boundYoutubeCapture, youtubeOwnershipUrl,
  youtubeVerificationInput, evaluateYoutubeOwnership, youtubeMusicKey} from './youtube-ownership-policy.mjs';

export const SHARED_CANDIDATE_PROPOSAL = 'youtube-shared-candidate-offline-v1';
export const sharedCandidatePolicyEnabled = false;
const unique = values => [...new Set(values)];
const facts = body => hash({displayName:body.displayName, description:body.description,
  externalUrls:unique(body.externalUrls ?? []).sort(),
  isAutoGenerated:body.isAutoGenerated ?? null, isOfficialArtistChannel:body.isOfficialArtistChannel ?? null});

// Extend ID comparison for the offline proposal only. Playlists are not artists.
function musicId(raw) {
  const key = youtubeMusicKey(raw);
  if (key?.startsWith('spotify:')) return key;
  try {
    const u = new URL(raw);
    if (u.protocol === 'https:' && !u.username && !u.password && !u.port
      && u.hostname === 'music.apple.com') {
      const match = u.pathname.match(/^\/(?:[a-z]{2}\/)?artist\/(?:[^/]+\/)?(\d+)\/?$/);
      if (match) return 'apple:' + match[1];
    }
  } catch { /* Not an artist ID. */ }
  return null;
}
function materialize(occurrence, index) {
  const {input} = occurrence;
  const {inputSha256, readyForModel, ...body} = input;
  assert.equal(hash(body), inputSha256, 'Changed original input');
  const {artist} = input.state;
  // A model-readable bound capture is not the original provider packet.
  // In particular, legacy alias resolution requires the original raw receipt.
  const candidate = occurrence.originalCandidate;
  assert.ok(candidate, 'Exact original candidate packet required');
  assert.equal(youtubeVerificationInput(artist, candidate).inputSha256, inputSha256,
    'Input does not bind this exact artist/channel pair');
  const capture = boundYoutubeCapture(candidate.url, candidate.capture);
  const pair = {profileId:String(artist.profileId), cmArtist:String(artist.cmArtist),
    channelId:capture?.body.channelId ?? null, url:youtubeOwnershipUrl(candidate.url)};
  const pairKey = hash(pair);
  const known = unique((artist.accounts ?? []).map(a => musicId(a.url ?? a.account_url)).filter(Boolean));
  const observed = unique((capture?.body.externalUrls ?? []).map(musicId).filter(Boolean));
  const conflictingMusicIds = observed.filter(id => known.some(k => k.split(':')[0] === id.split(':')[0])
    && !known.includes(id));
  const claims = [];
  const hasChannel = link => capture?.aliases.includes(youtubeOwnershipUrl(link));
  for (const declaration of artist.declarations ?? []) {
    if (declaration.status === 200 && declaration.body
      && declaration.bodySha256 === hash(declaration.body)
      && Number.isFinite(Date.parse(declaration.capturedAt))
      && declaration.body.sourceUrl === declaration.requestedUrl
      && (artist.accounts ?? []).some(a => (a.url ?? a.account_url) === declaration.requestedUrl)
      && (declaration.body.declaredLinks ?? []).some(hasChannel))
      claims.push({kind:'captured_catalog_account_declaration', source:declaration});
  }
  // youtubeVerificationInput above validates supplemental record and account bindings.
  for (const declaration of artist.ownershipEvidence?.declarations ?? []) {
    if (Number.isFinite(Date.parse(declaration.sourceUpdatedAt))
      && (declaration.declaredLinks ?? []).some(hasChannel))
      claims.push({kind:'catalog_account_declaration_not_independently_verified', source:declaration});
  }
  for (const id of observed.filter(id => known.includes(id)))
    claims.push({kind:'channel_music_id_matches_catalog_not_independently_verified', id,
      captureSha256:capture.bodySha256});
  return {occurrence, index, input, artist, candidate, capture, pair, pairKey,
    known, observed, conflictingMusicIds, claims};
}

export function compareSharedYoutubeCandidates(occurrences) {
  const rows = occurrences.map(materialize);
  return rows.map(row => {
    // Only a source-bound channel ID unifies aliases. Matching names never do.
    const peers = row.capture ? rows.filter(r => r.capture?.body.channelId === row.pair.channelId) : [row];
    const identities = unique(peers.map(r => r.pair.cmArtist));
    const sharedDiscovery = unique(peers.map(r => r.pair.profileId)).length > 1;
    const duplicateCatalogIdentities = peers.filter(r => r.index !== row.index
      && r.pair.cmArtist === row.pair.cmArtist).map(r => r.pair);
    const claims = peers.flatMap(r => r.claims.map(claim => ({pair:r.pair, inputSha256:r.input.inputSha256, ...claim})));
    const competingClaims = unique(claims.map(c => c.pair.cmArtist)).length > 1;
    const contradictory = peers.some(r => r.occurrence.contradictoryPair
      || (r.occurrence.channelAliasObservations ?? []).some(o => {
        const bound = boundYoutubeCapture(o.url, o.capture);
        return bound && facts(bound.body) !== facts(r.capture.body);
      })) || unique(peers.filter(r => r.capture).map(r => facts(r.capture.body))).length > 1;
    const catalogIdentityConflict = peers.some(r => r.pair.profileId === row.pair.profileId
      && r.pair.cmArtist !== row.pair.cmArtist);
    // Preserve every existing non-sharing gate. No answers or direct-link result
    // can turn this comparison into an ownership decision.
    const independentGate = evaluateYoutubeOwnership(row.artist, row.candidate,
      {contradictoryPair:contradictory});
    const held = !['needs_identity_check', 'likely_artist_owned'].includes(independentGate.status);
    const proposedRoute = !row.capture ? 'hold_unbound_channel'
      : catalogIdentityConflict ? 'hold_catalog_identity_conflict'
      : contradictory ? 'hold_contradictory_evidence'
      : row.conflictingMusicIds.length ? 'hold_conflicting_music_ids'
      : competingClaims ? 'hold_competing_source_supported_claims'
      : held ? 'hold_existing_nonsharing_gate'
      : 'artist_specific_identity_review_required';
    const reviewState = {proposal:SHARED_CANDIDATE_PROPOSAL, pair:row.pair,
      originalInput:row.input, sharedDiscovery, distinctCatalogMusicIdentities:identities,
      duplicateCatalogIdentities, sourceSupportedClaims:claims,
      peerEvidence:peers.map(r => ({pair:r.pair, inputSha256:r.input.inputSha256,
        input:r.input, contradictoryPair:r.occurrence.contradictoryPair ?? false,
        channelAliasObservations:r.occurrence.channelAliasObservations ?? []})),
      conflictingMusicIds:row.conflictingMusicIds, contradictory, catalogIdentityConflict};
    return {occurrence:row.index, pair:row.pair, pairKey:row.pairKey,
      originalInputSha256:row.input.inputSha256,
      historicalDecision:row.occurrence.historicalDecision ?? null,
      historicalAnswer:row.occurrence.recordedAnswer ?? null,
      historicalAnswerBinding:!row.occurrence.recordedAnswer ? 'no_recorded_answer'
        : row.occurrence.recordedAnswer.inputSha256 === row.input.inputSha256
          ? 'exact_original_input_only_not_reused_for_proposal' : 'wrong_original_input_not_reusable',
      independentGate, proposedRoute, reviewState,
      assessmentSha256:hash(reviewState),
      policyEnabled:false, approvalRequired:true, ownership:'unknown',
      reviewSuggestion:false, liveLinkAccepted:false, modelChecksPerformed:0};
  });
}
