function coordinator(){
  let admissions=[],reserved=0,before;
  const scope={artists:Array.from({length:100},(_,i)=>({profile_id:String(i+1)})),
    scopeSha256:'a'.repeat(64),maxCalls:500,explicitApproval:true,approvalStatus:'approved',
    proposedCapCents:1000,operationalCapCents:1000,userCapCents:1000};
  const run={owner:'owner',status:'running',scope_sha256:scope.scopeSha256,cap_cents:1000};
  const c={release(){},async query(sql,a=[]){
    sql=sql.replace(/\s+/g,' ').trim();
    if(sql==='BEGIN'){before=structuredClone({admissions,reserved});return {};}
    if(sql==='ROLLBACK'){({admissions,reserved}=before);return {};}
    if(sql==='COMMIT')return {};
    if(sql.includes('SELECT status FROM youtube_link_campaigns'))return {rows:[{status:'stopped'}]};
    if(sql.startsWith('SELECT * FROM youtube_discovery_test_runs'))return {rows:[{...run,reserved_cents:reserved}]};
    if(sql.includes('SELECT operation_key,kind,status'))return {rows:admissions.filter(r=>r.run_id===a[0]&&r.profile_id===a[1])};
    if(sql.startsWith('SELECT count(*)')){
      const ownPending=sql.includes('youtube_bounded_test_admissions')&&sql.includes("status='admitted'");
      return {rows:[{n:ownPending?admissions.filter(r=>r.status==='admitted').length:0}]};
    }
    if(sql.startsWith('INSERT INTO youtube_bounded_test_admissions')){
      admissions.push({run_id:a[0],operation_key:a[1],profile_id:a[2],kind:a[3],
        input_sha256:a[4],status:'admitted'});return {rowCount:1};
    }
    if(sql.startsWith('UPDATE youtube_discovery_test_runs SET reserved_cents')){
      if(reserved+2>1000)return {rowCount:0};reserved+=2;return {rowCount:1};
    }
    if(sql.startsWith("UPDATE youtube_bounded_test_admissions a SET status='returned'")){
      const r=admissions.find(r=>r.run_id===a[0]&&r.operation_key===a[1]&&r.profile_id===a[2]&&
        r.input_sha256===a[3]&&r.status==='admitted'&&run.owner===a[4]&&run.status==='running');
      if(!r)return {rowCount:0};r.status='returned';r.receipt_sha256=a[5];r.http_status=a[6];return {rowCount:1};
    }
    throw Error('Unexpected SQL '+sql);
  }};
  const pool={connect:async()=>c,query:(sql,a)=>c.query(sql,a)};
  const gate=reviewBatchGate({pool,plan:{id:'synthetic',parentId:'parent'},approval:scope,owner:'owner'});
  return {gate,rows:()=>admissions,budget:()=>reserved,setBudget:n=>{reserved=n;}};
}
test('stateful coordinator enforces call order, uncertain-request stop, owner binding and the shared $10 allowance',async()=>{
  const f=coordinator(),search={profileId:'1',kind:'search',key:'search-1-0',inputSha256:'b'.repeat(64)};
  await assert.rejects(f.gate.admit({...search,kind:'metadata',key:'metadata-1-0'}));
  assert.equal(f.rows().length,0);await f.gate.admit(search);
  await assert.rejects(f.gate.admit({...search,profileId:'2',key:'search-2-0'}));
  await assert.rejects(f.gate.returned({...search,inputSha256:'c'.repeat(64)},'d'.repeat(64),200));
  assert.equal(f.rows()[0].status,'admitted');
  await f.gate.returned(search,'d'.repeat(64),200);
  await assert.rejects(f.gate.admit({...search,key:'search-1-1'}));
  for(const [kind,key] of [['metadata','metadata-1-a'],['metadata','metadata-1-b'],
    ['model','model-1-a'],['model','model-1-b']]){
    const op={...search,kind,key};await f.gate.admit(op);await f.gate.returned(op,'d'.repeat(64),200);
  }
  assert.equal(f.rows().length,5);assert.equal(f.budget(),10);
  await assert.rejects(f.gate.admit({...search,kind:'model',key:'model-1-c'}));
  f.setBudget(1000);await assert.rejects(f.gate.admit({...search,profileId:'2',key:'search-2-0'}));
  assert.equal(f.rows().length,5);assert.equal(f.budget(),1000);
});
