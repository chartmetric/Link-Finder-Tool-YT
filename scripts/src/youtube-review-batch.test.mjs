function packet(kind,key,request,data){
  const raw=Buffer.from(JSON.stringify(data));
  return {runId:'synthetic',kind,operationKey:key,inputSha256:digest(request),request,status:200,
    data,at:'2026-11-17T00:00:00Z',sourcePath:'synthetic.json',
    rawBodySha256:digest(raw),rawBodyBase64:raw.toString('base64')};
}
function provider({videos=false,topic=false,twoChannels=false}={}){
  const calls=[];
  const request=async(id,kind,key,req)=>{
    calls.push({id,kind,key,req});
    let data;
    if(kind==='search')data={organic:videos?[
      {link:'https://www.youtube.com/watch?v=abcdefghijk',title:'Example Artist - New track (Official Audio)',snippet:'Example Artist music'}
    ]:[
      {link:url,title:'Example Artist'+(topic?' - Topic':''),snippet:'Example Artist music'},
      {link:twoChannels?'https://www.youtube.com/channel/UC'+'b'.repeat(22):'https://www.youtube.com/@exampleartist',
        title:'Example Artist',snippet:'Example Artist songs'},
    ]};
    else if(kind==='metadata'&&req.url.includes('/video?'))data={
      success:true,id:'abcdefghijk',title:'Example Artist - New track (Official Audio)',description:'Original music',
      channel:{id:channelId,title:'Example Artist'},uploader:{channelId},ownerByline:{channelId}};
    else if(kind==='metadata'){
      const requested=new URL(req.url).searchParams.get('url');
      const second=requested.includes('UC'+'b'.repeat(22));
      data={success:true,channelId:second?'UC'+'b'.repeat(22):channelId,
        channel:second?'https://www.youtube.com/channel/UC'+'b'.repeat(22):'https://www.youtube.com/@exampleartist',
        name:'Example Artist'+(topic?' - Topic':''),description:'Original artist music',
        links:[],isAutoGenerated:topic,credits_charged:1};
    }else data={model:'typesafe/jev-1.13-20260917',usage:{cost:.0001},
      answers:{combined_assessment:{type:'choice',choice:topic?'topic_identity_supported':'identity_uncertain'}}};
    return packet(kind,key,req,data);
  };
  return {calls,request};
}
