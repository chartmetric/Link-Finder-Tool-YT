// Read-only audit of exact archived decisions. No provider calls or regrading.
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {connectSavedBatchPool} from './instagram-saved-batch-gate.mjs';
import {CAMPAIGNS,readJson,saveJson} from './campaign-parallel-core.mjs';
import {evidenceDigest as hash} from './youtube-ownership-policy.mjs';
import {normalizeYoutubeChannel} from './youtube-ownership-transport.mjs';

const add=(out,k)=>{out[k]=(out[k]??0)+1;};
function musicKey(raw){
  try{
    const u=new URL(raw),host=u.hostname.replace(/^www\./,''),parts=u.pathname.split('/').filter(Boolean);
    if(u.protocol!=='https:'||u.username||u.password||u.port)return null;
    if(host==='open.spotify.com'&&parts.length===2&&parts[0]==='artist')return 'spotify:'+parts[1];
    if(host==='instagram.com'&&parts.length===1)return 'instagram:'+parts[0].toLowerCase();
  }catch{}return null;
}
export async function auditYoutube(){
  const cfg=CAMPAIGNS.youtube,pool=await connectSavedBatchPool();
  let rows,run,admissions;
  try{
    const c=await pool.connect();
    try{
      await c.query('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY');
      run=(await c.query('SELECT status,stop_reason,reserved_cents FROM youtube_link_campaigns WHERE id=$1',[cfg.id])).rows[0];
      assert.equal(run.status,'stopped','Audit a paused campaign, not moving counters.');
      rows=(await c.query('SELECT * FROM youtube_link_campaign_artists WHERE campaign_id=$1 ORDER BY ordinal',[cfg.id])).rows;
      admissions=(await c.query(`SELECT operation_key,profile_id,kind,status,receipt_sha256,http_status,created_at
        FROM youtube_link_campaign_admissions WHERE campaign_id=$1 ORDER BY operation_key`,[cfg.id])).rows;
      assert.ok(admissions.every(a=>a.status==='returned'));
      await c.query('COMMIT');
    }catch(e){await c.query('ROLLBACK').catch(()=>{});throw e;}finally{c.release();}
  }finally{await pool.end();}
  const report={at:new Date().toISOString(),campaignId:cfg.id,paused:true,noProviderRequests:true,
    totalArtists:rows.length,completed:0,checked:0,likely:0,notAccepted:0,noCandidates:0,unresolvedArtists:0,
    topicOnlyArtists:0,artistsWithTopicCandidate:0,likelyUnknownRoleArtists:0,
    missingReleases:0,missingCountry:0,noOfficialSourceCaptures:0,candidateCount:0,
    candidateReasons:{},modelVerdicts:{},modelRoles:{},rawMetadata:{successful:0,missingOfficialArtistBadge:0,missingAutoGeneratedFlag:0},
    legacyCapturesRecovered:0,artistsWithRecoverableCaptures:0,unacceptedArtistsWithKnownMusicLinks:0,
    newWave:{completed:0,checked:0,likely:0,reasons:{}},reservedCents:Number(run.reserved_cents),
    admissions:admissions.length,pendingAdmissions:0,failed:rows.filter(a=>a.status==='failed').length,
    unfinished:rows.filter(a=>a.status==='in_progress').length};
  const packets=new Map();
  for(const a of admissions.filter(a=>a.kind==='metadata')){
    const packet=await readJson(cfg.root+'/receipts/'+hash(a.operation_key)+'.json');
    assert.equal(hash(packet),a.receipt_sha256);assert.equal(packet.operationKey,a.operation_key);
    packets.set(a.operation_key,packet);
    if(packet.status===200){
      report.rawMetadata.successful++;
      if(typeof packet.data?.isOfficialArtistChannel!=='boolean')report.rawMetadata.missingOfficialArtistBadge++;
      if(typeof packet.data?.isAutoGenerated!=='boolean')report.rawMetadata.missingAutoGeneratedFlag++;
    }
  }
  const phases=await Promise.all((await fs.readdir(cfg.root)).filter(x=>x.startsWith('parallel-'))
    .map(name=>readJson(cfg.root+'/'+name+'/approval.json').catch(e=>{if(e.code==='ENOENT')return null;throw e;})));
  const since=phases.filter(Boolean).sort((a,b)=>Date.parse(b.at)-Date.parse(a.at))[0]?.at;
  const newProfiles=new Set(admissions.filter(a=>since&&Date.parse(a.created_at)>=Date.parse(since)).map(a=>a.profile_id));
  const likelyUnknown=[],recoverableArtists=new Set(),corroboratedArtists=new Set(),recent=[];
  for(const a of rows.filter(a=>a.status==='completed')){
    const r=await readJson(cfg.root+'/artists/'+a.profile_id+'.json');
    assert.equal(hash(r),a.result_sha256);assert.equal(r.artist.profileId,a.profile_id);
    const fresh=newProfiles.has(a.profile_id);
    report.completed++;report.checked+=Number(a.checked);report.likely+=Number(a.likely);
    report.notAccepted+=Number(a.checked&&!a.likely);report.candidateCount+=r.candidates.length;
    report.noCandidates+=Number(!r.candidates.length);
    report.missingReleases+=Number(!r.artist.releases?.length);report.missingCountry+=Number(!r.artist.country);
    report.noOfficialSourceCaptures+=Number(!r.artist.declarations?.length);
    report.unresolvedArtists+=Number(!a.likely&&r.candidates.some(c=>['needs_identity_check','needs_channel_metadata'].includes(c.decision.status)));
    report.artistsWithTopicCandidate+=Number(r.candidates.some(c=>c.decision.channelType==='topic'));
    report.topicOnlyArtists+=Number(!!r.candidates.length&&r.candidates.every(c=>c.decision.channelType==='topic'));
    const unknown=r.candidates.filter(c=>c.recordedAnswer?.answer.verdict==='likely'&&c.recordedAnswer?.answer.channelType==='unknown');
    if(!a.likely&&unknown.length){report.likelyUnknownRoleArtists++;likelyUnknown.push({artist:r.artist.name,candidates:unknown.length});}
    if(fresh){report.newWave.completed++;report.newWave.checked+=Number(a.checked);report.newWave.likely+=Number(a.likely);
      recent.push({artist:r.artist.name,likely:a.likely,reasons:r.candidates.map(c=>c.decision.reason)});}
    const known=new Set((r.artist.accounts??[]).map(x=>musicKey(x.url??x.account_url)).filter(Boolean));
    for(const c of r.candidates){
      add(report.candidateReasons,c.decision.reason);
      if(fresh)add(report.newWave.reasons,c.decision.reason);
      if(c.recordedAnswer){add(report.modelVerdicts,c.recordedAnswer.answer.verdict);add(report.modelRoles,c.recordedAnswer.answer.channelType);}
      const packet=packets.get('channel-'+a.profile_id+'-'+hash(c.url));
      if(!packet)continue;
      // Reconstruct metadata only. Never bind an old answer to a new input.
      const recovered=normalizeYoutubeChannel(packet,c.url);
      if(!c.capture&&recovered){report.legacyCapturesRecovered++;recoverableArtists.add(a.profile_id);}
      const body=c.capture?.body??recovered?.body;
      if(!a.likely&&(body?.externalUrls??[]).some(url=>known.has(musicKey(url))))corroboratedArtists.add(a.profile_id);
    }
  }
  report.artistsWithRecoverableCaptures=recoverableArtists.size;
  report.unacceptedArtistsWithKnownMusicLinks=corroboratedArtists.size;
  report.successRate=report.checked?100*report.likely/report.checked:null;
  const output=cfg.root+'/quality-audit-'+Date.now();await fs.mkdir(output);
  await saveJson(output+'/summary.json',report);
  await saveJson(output+'/review-examples.json',{likelyUnknownRole:likelyUnknown,newWave:recent,
    warning:'Unresolved examples are not independently confirmed correct links. No new model checks were made.'});
  console.log(JSON.stringify({output,...report},null,2));return report;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await auditYoutube();
