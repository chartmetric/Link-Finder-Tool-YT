import assert from 'node:assert/strict';
import {evidenceDigest,youtubeOwnershipUrl,boundYoutubeCapture,returnedYoutubeUrl} from './youtube-ownership-policy.mjs';
const badgeFields=['isAutoGenerated','isOfficialArtistChannel','isVerified'];
function youtubeBadgeMetadata(raw){
  // Only a source boolean is a known flag. Preserve null/malformed values and
  // absence separately; generic verification never supplies an artist badge.
  const sourceFields=Object.fromEntries(badgeFields.map(field=>[field,
    Object.hasOwn(raw,field)?{present:true,value:raw[field]}:{present:false}]));
  return {...Object.fromEntries(badgeFields.map(field=>[field,
    sourceFields[field].present&&typeof raw[field]==='boolean'?raw[field]:null])),
    badgeSourceFields:sourceFields};
}
export function normalizeYoutubeChannel(packet,requestedUrl){
  const raw=packet.data;
  if(packet.status!==200||raw?.success!==true)return null;
  if(!/^UC[A-Za-z0-9_-]{22}$/.test(raw.channelId??''))return null;
  const url=returnedYoutubeUrl(raw.channel);
  // Never hide an explicitly invalid returned address behind a channel-ID URL.
  if(raw.channel!=null&&!url)return null;
  const handle=url?.match(/\/@([^/]+)$/u)?.[1]??null;
  const body={channelId:raw.channelId,handle,
    url:url??'https://www.youtube.com/channel/'+raw.channelId,
    displayName:typeof raw.name==='string'?raw.name:'',
    description:typeof raw.description==='string'?raw.description:'',
    externalUrls:Array.isArray(raw.links)?raw.links.filter(v=>typeof v==='string'):[],
    subscribers:Number.isFinite(raw.subscriberCount)?raw.subscriberCount:null,
    country:typeof raw.country==='string'?raw.country:null,
    tags:typeof raw.tags==='string'?raw.tags:null,
    ...youtubeBadgeMetadata(raw)};
  const capture={status:200,requestedUrl,capturedAt:packet.at,body,
    bodySha256:evidenceDigest(body),rawReceiptSha256:evidenceDigest(packet),
    ...(/\/(?:c|user)\//.test(youtubeOwnershipUrl(requestedUrl)??'')||Array.isArray(raw.videos)?{rawReceipt:packet}:{})};
  return boundYoutubeCapture(requestedUrl,capture)?capture:null;
}
export function youtubeDecisionRequest(input,plan){
  assert.equal(input.readyForModel,true);
  const request={method:'POST',url:plan.model.endpoint,body:{
    model:plan.model.expectedModel,
    state:{...input.state,evidenceRules:input.rules},
    questions:{
      same_identity:{type:'noul',instructions:'Apply evidenceRules to this exact artist and candidate. Is this artist-owned, not merely associated?',
        criteria:{true:'Combined evidence supports exact artist ownership.',false:'Different identity or related entity.'}},
      verdict:{type:'choice',instructions:'Apply evidenceRules to all supplied evidence. Missing evidence is uncertainty, not mismatch.',
        criteria:{likely:'Supporting evidence for exact artist ownership.',uncertain:'Insufficient evidence.',mismatch:'Evidence of another identity or entity.'}},
      channel_type:{type:'choice',instructions:'Classify the candidate channel itself using the captured evidence, not names alone.',
        criteria:{artist_owned:'Owned by this exact artist.',topic:'Auto-generated music catalog channel.',
          fan:'Fan or tribute channel.',organization:'Label, agency, venue or other organization.',
          unrelated:'Another person or music identity.',unknown:'Channel role cannot be determined.'}},
    }}};
  const bytes=Buffer.byteLength(JSON.stringify(request.body));
  return {request,bytes,ready:bytes<=plan.model.maxRequestBytes,inputSha256:evidenceDigest(request)};
}
export function parseYoutubeDecision(packet,input,plan,requestHash){
  const d=packet.data;
  // A receipt hash alone does not bind an answer to the supplied artist/evidence.
  // Verify the complete policy input, regenerate the exact typed request, and
  // compare the saved outgoing bytes before allowing the answer to be attached.
  assert.equal(input.inputSha256,evidenceDigest({policy:input.policy,rules:input.rules,state:input.state}));
  assert.equal(youtubeDecisionRequest(input,plan).inputSha256,requestHash);
  assert.equal(evidenceDigest(packet.request),requestHash);
  assert.equal(packet.inputSha256,requestHash);
  assert.equal(packet.status,200);
  assert.ok(!d?.error);
  // The requested alias legitimately resolves to this observed dated release.
  // Keep an exact allowlist, not a permissive prefix or arbitrary model fallback.
  assert.ok([plan.model.expectedModel,
    ...(plan.model.expectedModel==='typesafe/jev-1.13'?['typesafe/jev-1.13-20260917']:[])].includes(d.model),
  'Unexpected resolved model; preserve the paid receipt and stop without replay.');
  assert.ok(Number.isFinite(d.usage?.cost)&&d.usage.cost>=0&&d.usage.cost<=.02,
    'Missing or out-of-bounds model billing evidence; stop without retry.');
  const a={sameIdentityProbability:d.answers?.same_identity?.noul,
    verdict:d.answers?.verdict?.choice,channelType:d.answers?.channel_type?.choice};
  assert.ok(Number.isFinite(a.sameIdentityProbability)&&a.sameIdentityProbability>=0&&a.sameIdentityProbability<=1);
  assert.ok(['likely','uncertain','mismatch'].includes(a.verdict));
  assert.ok(['artist_owned','topic','fan','organization','unrelated','unknown'].includes(a.channelType));
  return {inputSha256:input.inputSha256,requestSha256:requestHash,answer:a,
    requestedModel:plan.model.expectedModel,resolvedModel:d.model,
    rawAnswers:d.answers,providerReportedUsd:d.usage.cost,receiptSha256:evidenceDigest(packet)};
}
export function providerStopReason(packet){
  // Search snippets, channel descriptions and model answers are content, not
  // provider diagnostics. A track named "Unauthorized" must not stop a run.
  const data=packet.data;
  const diagnostics=typeof data==='string'?data:
    data&&typeof data==='object'?Object.fromEntries(
      ['error','errors','message','detail','status'].filter(k=>Object.hasOwn(data,k)).map(k=>[k,data[k]])
    ):{};
  const serialized=JSON.stringify(diagnostics);
  if(/insufficient.{0,30}(?:credit|balance)|not enough credits|payment required|credit.{0,15}exhaust|billing limit/i.test(serialized)
    ||packet.status===402)return 'provider_funding_failure';
  if([401,403].includes(packet.status)||/invalid.{0,10}api.?key|unauthorized|authentication failed/i.test(serialized))
    return 'provider_authentication_or_access_failure';
  if(packet.status===429)return 'provider_rate_limit';
  if(packet.status>=300&&packet.status<400)return 'unexpected_provider_redirect';
  if(packet.parseFailed)return 'unreadable_provider_response';
  if(packet.status===200&&(packet.data?.error||packet.data?.success===false))return 'provider_protocol_failure';
  return null;
}
export function youtubeOwnershipTransport({gate,archiveDir,assertFrozen,fetchImpl=fetch,credentials}){
  return async function request(operation,request){
    await assertFrozen();
    const inputSha256=evidenceDigest(request),op={...operation,inputSha256};
    if(operation.kind==='metadata'){
      const u=new URL(request.url);
      assert.equal(u.origin,'https://api.scrapecreators.com');assert.equal(u.pathname,'/v1/youtube/channel');
      assert.equal(request.method,'GET');assert.equal(request.body,undefined);
      assert.equal(u.searchParams.size,1);assert.ok(youtubeOwnershipUrl(u.searchParams.get('url')));
    }else{
      assert.equal(operation.kind,'model');assert.equal(request.url,'https://openrouter.ai/api/alpha/decisions');
      assert.equal(request.method,'POST');assert.ok(Buffer.byteLength(JSON.stringify(request.body))<=6000);
    }
    await gate.admit(op);
    // An admission survives a missing journal, missing response or process exit.
    await fs.appendFile(archiveDir+'/admissions.jsonl',JSON.stringify({...op,at:new Date().toISOString(),reservedCents:2})+'\n');
    const response=await fetchImpl(request.url,{method:request.method,redirect:'error',
      signal:AbortSignal.timeout(30000),
      headers:operation.kind==='metadata'?{'x-api-key':credentials.scrapecreators}:
        {Authorization:'Bearer '+credentials.openrouter,'Content-Type':'application/json'},
      ...(request.body?{body:JSON.stringify(request.body)}:{})});
    const chunks=[];let bytes=0;
    if(response.body)for await(const chunk of response.body){
      bytes+=chunk.length;if(bytes>2000000)throw Error('Oversized response; uncertain request will not be replayed.');
      chunks.push(chunk);
    }
    const text=Buffer.concat(chunks).toString('utf8');
    let data=null,parseFailed=false;try{data=JSON.parse(text);}catch{parseFailed=true;}
    const packet={at:new Date().toISOString(),kind:operation.kind,operationKey:operation.key,
      status:response.status,inputSha256,request,data,parseFailed,...(parseFailed?{rawText:text}:{})};
    const receiptHash=evidenceDigest(packet);
    await fs.writeFile(archiveDir+'/receipts/'+evidenceDigest(operation.key)+'.json',JSON.stringify(packet,null,2),{flag:'wx'});
    await gate.returned(op,receiptHash,response.status);
    const reason=providerStopReason(packet);
    if(reason)throw Error(reason);
    return packet;
  };
}
