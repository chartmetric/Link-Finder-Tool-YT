import test from 'node:test';
import assert from 'node:assert/strict';
import {normalizeYoutubeChannel,youtubeDecisionRequest} from './youtube-ownership-transport.mjs';
import {evidenceDigest,youtubeVerificationInput,evaluateYoutubeOwnership} from './youtube-ownership-policy.mjs';

const url='https://www.youtube.com/@artist';
const spotify='https://open.spotify.com/artist/'+'a'.repeat(22);
const artist={profileId:'1',cmArtist:'2',name:'Artist',
  catalogProfile:{profile_id:'1',cm_artist:'2'},accounts:[{url:spotify}]};
const model={endpoint:'https://openrouter.ai/api/alpha/decisions',
  expectedModel:'typesafe/jev-1.13',maxRequestBytes:6000};
const fields=['isOfficialArtistChannel','isAutoGenerated','isVerified'];
function packet(patch={}){
  return {status:200,at:'2026-11-11T00:00:00Z',data:{success:true,
    channelId:'UC'+'a'.repeat(22),channel:url,name:'Artist',
    description:'Musician',links:[spotify],...patch}};
}
function candidate(patch={}){
  return {url,capture:normalizeYoutubeChannel(packet(patch),url)};
}
function positive(c){
  return {inputSha256:youtubeVerificationInput(artist,c).inputSha256,
    answer:{verdict:'likely',channelType:'artist_owned',sameIdentityProbability:.37}};
}

for(const field of fields){
  for(const value of [true,false,null,'false','true',0,1,{},[]]){
    test(`${field}: preserve explicit ${JSON.stringify(value)} without boolean coercion`,()=>{
      const raw=packet({[field]:value}),before=structuredClone(raw);
      const capture=normalizeYoutubeChannel(raw,url);
      assert.equal(capture.body[field],typeof value==='boolean'?value:null);
      assert.deepEqual(capture.body.badgeSourceFields[field],{present:true,value});
      assert.deepEqual(raw,before,'Normalization must not modify the source receipt.');
      assert.equal(capture.rawReceiptSha256,evidenceDigest(raw));
      assert.equal(capture.bodySha256,evidenceDigest(capture.body));
      const input=youtubeVerificationInput(artist,{url,capture});
      const prepared=youtubeDecisionRequest(input,{model});
      assert.equal(prepared.ready,true);
      const body=JSON.parse(JSON.stringify(prepared.request)).body.state.candidate.channelCapture.body;
      assert.equal(body[field],typeof value==='boolean'?value:null);
      assert.deepEqual(body.badgeSourceFields[field],{present:true,value});
    });
  }
  test(`${field}: absence remains unknown through serialized model input`,()=>{
    const c=candidate();
    const prepared=youtubeDecisionRequest(youtubeVerificationInput(artist,c),{model});
    const body=JSON.parse(JSON.stringify(prepared.request)).body.state.candidate.channelCapture.body;
    assert.equal(body[field],null);
    assert.deepEqual(body.badgeSourceFields[field],{present:false});
    assert.equal(Object.hasOwn(body.badgeSourceFields[field],'value'),false);
  });
}

test('Generic verification cannot supply an artist badge or auto-generated status',()=>{
  for(const isVerified of [true,false]){
    const c=candidate({isVerified});
    assert.equal(c.capture.body.isVerified,isVerified);
    assert.equal(c.capture.body.isOfficialArtistChannel,null);
    assert.equal(c.capture.body.isAutoGenerated,null);
    assert.deepEqual(c.capture.body.badgeSourceFields.isOfficialArtistChannel,{present:false});
    assert.equal(evaluateYoutubeOwnership(artist,c).reviewSuggestion,false);
    assert.equal(candidate({isVerified,isOfficialArtistChannel:false}).capture.body.isOfficialArtistChannel,false);
    assert.equal(candidate({isVerified,isOfficialArtistChannel:true}).capture.body.isOfficialArtistChannel,true);
  }
  const request=youtubeDecisionRequest(youtubeVerificationInput(artist,candidate({isVerified:true})),{model});
  assert.match(request.request.body.state.evidenceRules,/null is unknown, not false/);
  assert.match(request.request.body.state.evidenceRules,/Generic isVerified is not Official Artist Channel status/);
});

test('Absent, false and explicit null sources bind to different inputs and reject stale answers',()=>{
  const absent=candidate(),explicitFalse=candidate({isOfficialArtistChannel:false}),
    explicitNull=candidate({isOfficialArtistChannel:null});
  const inputs=[absent,explicitFalse,explicitNull].map(c=>youtubeVerificationInput(artist,c));
  assert.equal(new Set(inputs.map(i=>i.inputSha256)).size,3);
  assert.equal(new Set(inputs.map(i=>youtubeDecisionRequest(i,{model}).inputSha256)).size,3);
  assert.equal(evaluateYoutubeOwnership(artist,absent,{answer:positive(explicitFalse)}).reviewSuggestion,false);
});

test('Badge states never remove Topic, fan, organization or conflicting-identity protections',()=>{
  for(const badges of [{},{isOfficialArtistChannel:false,isAutoGenerated:false},
    {isOfficialArtistChannel:true,isVerified:true}]){
    for(const [patch,status,type] of [
      [{name:'Artist - Topic'},'related_catalog_channel','topic'],
      [{description:'Auto-generated by YouTube.'},'related_catalog_channel','topic'],
      [{isAutoGenerated:true},'related_catalog_channel','topic'],
      [{description:'Fan channel for Artist'},'not_artist_owned','fan'],
      [{description:'Independent record label'},'not_artist_owned','organization'],
      [{links:['https://open.spotify.com/artist/'+'b'.repeat(22)]},'ownership_conflict','unknown'],
    ]){
      const c=candidate({...badges,...patch});
      const result=evaluateYoutubeOwnership(artist,c,{answer:positive(c)});
      assert.equal(result.status,status);assert.equal(result.channelType,type);
      assert.equal(result.reviewSuggestion,false);assert.equal(result.liveLinkAccepted,false);
    }
    const c=candidate(badges);
    assert.equal(evaluateYoutubeOwnership(artist,c).reviewSuggestion,false,'Badges alone are insufficient.');
    const result=evaluateYoutubeOwnership(artist,c,{answer:positive(c)});
    assert.equal(result.reviewSuggestion,true,'No new badge requirement or score threshold.');
    assert.equal(result.score,.37);assert.equal(result.liveLinkAccepted,false);
    assert.equal(evaluateYoutubeOwnership(artist,c,{sharedChannel:true,answer:positive(c)}).status,'ownership_conflict');
    assert.equal(evaluateYoutubeOwnership(artist,c,{contradictoryPair:true,answer:positive(c)}).status,'ownership_conflict');
  }
});
