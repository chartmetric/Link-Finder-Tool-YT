// Discovery relevance only: these clues never establish account ownership.
import {createHash} from 'node:crypto';
const norm=v=>String(v??'').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu,' ').trim();
const identity=v=>norm(v).replaceAll(' ','');
const recordHash=row=>createHash('sha256').update(JSON.stringify(row)).digest('hex');
export function youtubeSearchNames(artist){
  const names=[{name:artist.name??artist.artist,source:'requested_catalog_artist'}];
  const bound=String(artist.catalogProfile?.profile_id)===String(artist.profileId)
    &&String(artist.catalogProfile?.cm_artist)===String(artist.cmArtist);
  if(bound){
    const cm=artist.context?.chartmetric;
    if(String(cm?.cm_artist)===String(artist.cmArtist)&&cm?.name)
      names.push({name:cm.name,source:'exact_cm_artist_catalog_name',profileId:String(artist.profileId),
        cmArtist:String(artist.cmArtist),sourceRecordSha256:recordHash(cm)});
    for(const row of artist.context?.spotify??[])
      if(row.usableAsContext===true&&String(row.profile_id)===String(artist.profileId)&&row.latest?.[0])
        names.push({name:row.latest[0],source:'bound_catalog_spotify_name',profileId:String(artist.profileId),
          cmArtist:String(artist.cmArtist),accountId:String(row.account_id),sourceRecordSha256:recordHash(row)});
  }
  return names.filter((r,i)=>norm(r.name)&&names.findIndex(x=>identity(x.name)===identity(r.name))===i);
}
export function youtubeArtistSearchQuery(artist){
  const name=String(artist.name??artist.artist??'').normalize('NFKC').replace(/["\\\r\n]/g,' ').replace(/\s+/g,' ').trim();
  if(!name)throw Error('Missing exact artist name for YouTube discovery');
  return `"${name}" musician music official YouTube channel`;
}
export function rankYoutubeMusicCandidates(artist,candidates){
  const names=youtubeSearchNames(artist);
  const observations=candidates.map((candidate,index)=>{
    const title=String(candidate.title??''),snippet=String(candidate.snippet??'');
    const header=title.replace(/\s*[-|]\s*YouTube\s*$/i,'').replace(/\s*[-|]?\s*(official(?: channel)?|topic)\s*$/i,'').trim();
    const named=names.find(n=>identity(n.name)===identity(header));
    const music=/\b(?:musician|singer|rapper|band|songs?|albums?|records?|official music|music videos?|producer|dj)\b/i.test(title+' '+snippet);
    const visual=/\b(?:drawing|painting)\s+(?:tutorials?|lessons?|courses?)\b|\bart instruction|\bart instructor|\bspeed drawings|\bportrait artist|\bhow to (?:draw|paint)\b|\bjoy of painting\b|\bpaint along\b/i.test(title+' '+snippet);
    const topic=/\s[-–—]\sTopic\s*$/i.test(title)||/auto.generated by youtube/i.test(snippet);
    const excluded=visual&&!music&&!named;
    const score=(named?10:0)+(music?3:0)-(visual?5:0);
    return {...candidate,discoveryRanking:{version:'music-search-v1',score,originalPosition:index,
      matchedName:named??null,roleHint:topic?'topic':'unknown',excludedFromCapture:excluded,
      reason:excluded?'visual_art_instruction_without_bound_artist_or_music_context':
        topic?'topic_separate_from_artist_channel':'discovery_clues_only_not_ownership'}};
  });
  const order=(a,b)=>b.discoveryRanking.score-a.discoveryRanking.score
    ||a.discoveryRanking.originalPosition-b.discoveryRanking.originalPosition;
  return {allCandidates:observations,candidates:observations.filter(c=>!c.discoveryRanking.excludedFromCapture
    &&c.discoveryRanking.roleHint!=='topic').sort(order),
    relatedTopicCandidates:observations.filter(c=>c.discoveryRanking.roleHint==='topic'),
    excludedCandidates:observations.filter(c=>c.discoveryRanking.excludedFromCapture)};
}
