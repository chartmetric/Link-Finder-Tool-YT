// Entirely synthetic identities, releases, receipts and answers. No archives,
// credentials, provider calls, database access or production execution.
const id='UC'+'q'.repeat(22),idUrl='https://www.youtube.com/channel/'+id;
const handleUrl='https://www.youtube.com/@syntheticartist';
const spotify='https://open.spotify.com/artist/'+'Q'.repeat(22);
const help='https://support.google.com/youtube/answer/2579942';
const model={endpoint:'https://openrouter.ai/api/alpha/decisions',
  expectedModel:'typesafe/jev-1.13',maxRequestBytes:24576};
function fixture({name='Synthetic Release',description='',links=[help],badges={},
  requestedUrl=idUrl,returnedUrl=idUrl,search={},aliases=[]}={}){
  const artist={profileId:'900001',cmArtist:'900002',name:'Synthetic Artist',aliases,
    catalogProfile:{profile_id:'900001',cm_artist:'900002'},
    accounts:[{profile_id:'900001',cm_artist:'900002',platform:'spotify',
      account_url:spotify,is_active:1,disconnected_at:null}],
    releases:[{cm_artist:'900002',track_name:'Synthetic Release'}]};
  const request={method:'GET',url:'https://api.scrapecreators.com/v1/youtube/channel?'
    +new URLSearchParams({url:requestedUrl})};
  const packet={kind:'metadata',status:200,at:'2026-11-18T00:00:00Z',
    request,inputSha256:evidenceDigest(request),data:{success:true,channelId:id,
      channel:returnedUrl,name,description,links,...badges}};
  const capture=normalizeYoutubeChannel(packet,requestedUrl);
  assert.ok(capture);
  const input=youtubeVerificationInput(artist,{url:requestedUrl,capture,...search});
  const prepared=youtubeDecisionRequest(input,{model});
  const original={key:'synthetic-collection',kind:'model',profileId:artist.profileId,
    cmArtist:artist.cmArtist,channelId:id,request:prepared.request,
    inputSha256:prepared.inputSha256,policyInputSha256:input.inputSha256,
    requestBytes:prepared.bytes,
    requestBodySha256:digest(Buffer.from(JSON.stringify(prepared.request.body))),
    proposedReservationCents:2};
  return {artist,packet,capture,original,proposal:artistRepresentationRequest(original,capture)};
}
function response(p,choice='topic_identity_supported'){
  return {kind:'model',status:200,request:structuredClone(p.request),inputSha256:p.requestSha256,
    profileId:p.originalOperation.profileId,cmArtist:p.originalOperation.cmArtist,channelId:id,
    data:{model:'typesafe/jev-1.13-20260917',usage:{cost:.0001},
      answers:{combined_assessment:{type:'choice',choice}}}};
}
function assertInert(result){
  for(const value of [result.executionEnabled,result.policyActivated,result.ownershipAccepted,
    result.importEligible,result.catalogWritten,result.decision.verified,
    result.decision.liveLinkAccepted])assert.equal(value,false);
}

test('normalization preserves collection facts; search-only artist attribution stays in searchEvidence',()=>{
  const f=fixture({search:{title:'Synthetic Artist - Topic',
    snippet:'Synthetic Release by Synthetic Artist. Official auto-generated artist channel.'}});
  const before=structuredClone(f.packet),body=f.proposal.request.body.state.candidate.channelCapture.body;
  assert.equal(body.displayName,'Synthetic Release');assert.equal(body.description,'');
  assert.deepEqual(body.externalUrls,[help]);
  assert.equal(body.isAutoGenerated,null);assert.equal(body.isOfficialArtistChannel,null);
  assert.equal(body.isVerified,null);
  assert.equal(f.proposal.request.body.state.candidate.searchEvidence.title,'Synthetic Artist - Topic');
  assert.deepEqual(normalizeYoutubeChannel(f.packet,f.capture.requestedUrl),f.capture);
  assert.deepEqual(f.packet,before);
  assert.equal(f.capture.bodySha256,evidenceDigest(f.capture.body));
  assert.equal(f.capture.rawReceiptSha256,evidenceDigest(f.packet));
});

test('reproduces legacy positive-Topic promotion, while the isolated proposal holds it without relabeling the model',()=>{
  const f=fixture({search:{title:'Synthetic Artist - Topic',snippet:'Synthetic Release by Synthetic Artist'}});
  const answer=response(f.proposal),before=structuredClone({f,answer});
  const legacy=parseArtistRepresentationResponse(f.proposal,answer);
  assert.equal(legacy.decision.reviewSuggestion,true,'Documents the unchanged permissive baseline');
  assert.equal(legacy.channelTypeLabel,'Topic — auto-generated');
  const result=reviewCollectionRepresentation(f.proposal,answer);
  assert.equal(result.decision.reviewSuggestion,false);
  assert.equal(result.decision.status,'experimental_safety_hold');
  assert.equal(result.decision.reason,'release_collection_channel_identity_unresolved');
  assert.equal(result.channelTypeLabel,'Unresolved — release collection or artist channel');
  assert.equal(result.modelAssessment.category,'topic_identity_supported');
  assert.deepEqual(result.modelAnswer,legacy.modelAnswer);
  assert.equal(result.collectionReview.searchEvidenceUsedForChannelIdentity,false);
  assert.equal(result.collectionReview.evidence.some(e=>e.meaning==='release_title_match_not_artist_identity'),true);
  assertInert(result);
  assert.deepEqual({f,answer},before,'No source, request, receipt or historical result mutation');
  assert.deepEqual(parseArtistRepresentationResponse(f.proposal,answer),legacy);
});

test('collection ambiguity survives unknown, false, malformed and positive badge fields',()=>{
  for(const badges of [{},{isAutoGenerated:null,isOfficialArtistChannel:null},
    {isAutoGenerated:'true',isOfficialArtistChannel:'false',isVerified:1},
    {isAutoGenerated:false,isOfficialArtistChannel:false,isVerified:false},
    {isAutoGenerated:true},{isOfficialArtistChannel:true,isVerified:true}]){
    const f=fixture({badges,links:[help,spotify]});
    for(const field of ['isAutoGenerated','isOfficialArtistChannel','isVerified']){
      const body=f.proposal.request.body.state.candidate.channelCapture.body;
      assert.equal(body[field],typeof badges[field]==='boolean'?badges[field]:null);
      assert.deepEqual(body.badgeSourceFields[field],Object.hasOwn(badges,field)
        ?{present:true,value:badges[field]}:{present:false});
    }
    for(const choice of ['topic_identity_supported','artist_representation_supported','artist_managed_supported']){
      const result=reviewCollectionRepresentation(f.proposal,response(f.proposal,choice));
      assert.equal(result.decision.reviewSuggestion,false);
      assertInert(result);
    }
  }
});

test('help article alone is not a collection verdict: genuine artist Topic pages remain eligible for review',()=>{
  for(const badges of [{},{isAutoGenerated:true},{isVerified:true},
    {isAutoGenerated:false,isOfficialArtistChannel:null}]){
    const f=fixture({name:'Synthetic Artist - Topic',description:'Auto-generated by YouTube.',
      links:[help,spotify],badges});
    const result=reviewCollectionRepresentation(f.proposal,response(f.proposal));
    assert.equal(result.collectionReview.ambiguous,false);
    assert.equal(result.collectionReview.establishesIdentity,false);
    assert.equal(result.decision.reviewSuggestion,true);
    assert.equal(result.channelTypeLabel,'Topic — auto-generated');
    assert.equal(result.modelAssessment.artistOwned,false);
    assertInert(result);
    assert.equal(reviewCollectionRepresentation(f.proposal,
      response(f.proposal,'artist_representation_supported')).decision.reviewSuggestion,false);
  }
});

test('titles and help URLs are not blacklists or automatic identity proof',()=>{
  const cases=[
    [{name:'Synthetic Release',links:[]},false],
    [{name:'Synthetic Release',links:['https://support.google.com.evil.example/youtube/answer/2579942']},false],
    [{name:'Synthetic Release',links:['https://support.google.com/youtube/answer/other']},false],
    [{name:'Synthetic Release',links:[help+'?hl=en']},true],
    [{name:'Different Release',links:[help]},true],
    [{name:'Synthetic Release - Topic'},true],
    [{name:'Synthetic Release',aliases:['Synthetic Release']},false],
    [{name:'Synthetic Artist',links:[help]},false],
  ];
  for(const [options,expected] of cases){
    const f=fixture(options);
    const evidence=collectionChannelEvidence(f.artist,f.capture.requestedUrl,f.capture);
    assert.equal(evidence.ambiguous,expected,JSON.stringify(options));
    assert.equal(evidence.establishesIdentity,false);
    assert.equal(evidence.establishesOwnership,false);
  }
});

test('captured ID/handle aliases bind only the observed channel and do not resolve channel type',()=>{
  const f=fixture({requestedUrl:handleUrl,returnedUrl:handleUrl});
  const bound=boundYoutubeCapture(handleUrl,f.capture);
  assert.deepEqual(new Set(bound.aliases),new Set([handleUrl,idUrl]));
  assert.equal(f.proposal.request.body.state.candidate.url,handleUrl);
  const result=reviewCollectionRepresentation(f.proposal,response(f.proposal));
  assert.equal(result.youtubeUrl,idUrl);
  assert.equal(result.collectionReview.ambiguous,true);
  assert.equal(result.decision.reviewSuggestion,false);
  for(const url of ['https://www.youtube.com/@unrelated','https://www.youtube.com/channel/UC'+'x'.repeat(22),
    'https://www.youtube.com/watch?v=abcdefghijk']){
    assert.equal(boundYoutubeCapture(url,f.capture),null);
    assert.equal(collectionChannelEvidence(f.artist,url,f.capture).status,'unbound_capture');
  }
  assert.equal(normalizeYoutubeChannel({...f.packet,data:{...f.packet.data,channel:idUrl}},handleUrl),null,
    'An unobserved handle is not inferred from a requested URL');
  const canonical=fixture({requestedUrl:idUrl,returnedUrl:handleUrl});
  assert.deepEqual(new Set(boundYoutubeCapture(idUrl,canonical.capture).aliases),new Set([idUrl,handleUrl]));
  assert.equal(reviewCollectionRepresentation(canonical.proposal,response(canonical.proposal))
    .decision.reviewSuggestion,false);
});

