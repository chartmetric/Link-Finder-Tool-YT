export type SavedYoutubeTest = {
  profile_id: string; cm_artist: string; status: string;
  candidates_json: unknown; checked_at: Date | string;
};
export type YoutubeCoverageEvidence = {
  profile_id: string; cm_artist: string; status: string;
  candidate_count: number; checked_at: Date;
};
const channelId = /^UC[A-Za-z0-9_-]{22}$/;
const positive = new Set(["artist_managed_supported", "topic_identity_supported", "artist_representation_supported"]);
type Json = Record<string, unknown>;
const object = (v: unknown): Json => v !== null && typeof v === "object" && !Array.isArray(v) ? v as Json : {};

function matchesCapturedChannel(value: unknown, requested: unknown, id: string) {
  if (value === `https://www.youtube.com/channel/${id}`) return true;
  if (typeof value !== "string" || value !== requested) return false;
  try {
    const u = new URL(value);
    const path = decodeURIComponent(u.pathname).replace(/\/$/, "");
    return u.protocol === "https:" && !u.username && !u.password && !u.port && !u.search && !u.hash
      && ["youtube.com", "www.youtube.com", "m.youtube.com", "music.youtube.com"].includes(u.hostname)
      && (path.startsWith("/channel/") ? path === `/channel/${id}` : /^\/(?:@[^/\s?#]+|(?:c|user)\/[^/\s?#]+)$/.test(path));
  } catch { return false; }
}

function suggestedChannel(candidate: unknown, row: SavedYoutubeTest) {
  const c = object(candidate), a = object(c.assessment), d = object(a.decision);
  const capture = object(c.capture), body = object(capture.body);
  const model = object(a.modelAssessment);
  const id = typeof body.channelId === "string" ? body.channelId : "";
  const url = `https://www.youtube.com/channel/${id}`;
  // The older combined checker called Topic support experimental_topic_support
  // while deliberately leaving its artist-management review flag false.
  const legacyTopic = a.version === "youtube-combined-ownership-offline-v1"
    && model.category === "topic_identity_supported" && d.status === "experimental_topic_support";
  if (c.status !== "review_suggestion" || (d.reviewSuggestion !== true && !legacyTopic)
    || a.profileId !== row.profile_id || a.cmArtist !== row.cm_artist
    || !channelId.test(id) || !matchesCapturedChannel(c.url, capture.requestedUrl, id) || a.youtubeUrl !== url
    || capture.status !== 200 || !positive.has(String(model.category))
    || c.sharedChannelConflict === true || c.contradictoryPair === true
    // These are saved worker assessments, not a new raw-receipt verification.
    // PostgreSQL jsonb reorders object keys, so JSON.stringify cannot recheck
    // the original wire/body hash here. Keep the stored receipt references.
    || !/^[a-f0-9]{64}$/.test(String(capture.bodySha256))
    || !/^[a-f0-9]{64}$/.test(String(capture.rawReceiptSha256))) return null;
  const topic = model.category === "topic_identity_supported";
  // A Topic/non-Topic contradiction is not a supported artist-facing channel.
  if (!topic && (body.isAutoGenerated === true || / - Topic$/i.test(String(body.displayName)))) return null;
  return { id, topic };
}

/** Read-only projection of saved results, never a new verification or approval. */
export function youtubeTestCoverage(rows: SavedYoutubeTest[]) {
  const claimed = new Map<string, Set<string>>();
  const prepared = rows.map(row => {
    if (!/^\d+$/.test(row.profile_id) || !/^\d+$/.test(row.cm_artist)
      || !Number.isFinite(new Date(row.checked_at).getTime()) || !Array.isArray(row.candidates_json))
      throw Error("Invalid saved YouTube coverage evidence.");
    const channels = ["review_processed", "source_processed"].includes(row.status)
      ? row.candidates_json.flatMap(c => { const value = suggestedChannel(c, row); return value ? [value] : []; }) : [];
    for (const c of channels) {
      const owners = claimed.get(c.id) ?? new Set<string>();
      owners.add(`${row.profile_id}:${row.cm_artist}`);
      claimed.set(c.id, owners);
    }
    return { row, channels };
  });
  return prepared.map(({ row, channels }): YoutubeCoverageEvidence => {
    const usable = channels.filter(c => claimed.get(c.id)!.size === 1);
    let status: string;
    if (["review_processed", "source_processed"].includes(row.status)) {
      if (usable.some(c => !c.topic)) status = "test_likely";
      else if (usable.length) status = "test_topic";
      else if ((row.candidates_json as unknown[]).length === 0) status = "no_match";
      else if ((row.candidates_json as unknown[]).every(c => object(c).status === "not_a_match")) status = "no_match";
      else status = "candidates_found"; // Holds, conflicts and incomplete captures are not links.
    } else if (["candidates_found", "no_match", "failed", "admitted"].includes(row.status)) status = row.status;
    else status = "admitted"; // Prepared/unknown states are incomplete, never no-match.
    return { profile_id: row.profile_id, cm_artist: row.cm_artist, status,
      candidate_count: status === "candidates_found" ? Math.max(1, (row.candidates_json as unknown[]).length) : usable.length,
      checked_at: new Date(row.checked_at) };
  });
}
